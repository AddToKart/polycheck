import {
  BadRequestException,
  ConflictException,
  ForbiddenException,
  Injectable,
  Logger,
  NotFoundException,
  Optional,
} from '@nestjs/common'
import type { AtRiskReferral, ReferralStatus } from '@polycheck/shared'
import type { RequestUser } from '../auth/authenticated-principal'
import { adminSectionWhere, adminSectionInScope } from '../common/admin-scope'
import { academicOversightDepartment } from '../common/designations/department-pin'
import { ErrorCode } from '../common/constants/error-codes'
import { lockStudentSection } from '../common/student-section-lock'
import type { Prisma } from '../prisma/client'
import { PrismaService } from '../prisma/prisma.service'
import { NotificationsService } from '../notifications/notifications.service'
import { AttendanceAtRiskService, isReferralEligible } from './attendance-at-risk.service'
import type { GenerateAtRiskReferralDto, UpdateAtRiskReferralDto } from './dto/attendance.dto'

const REFERRAL_LIST_LIMIT = 100

type ReferralRow = Prisma.AtRiskReferralGetPayload<{
  include: {
    student: { select: { id: true; studentId: true; fullName: true } }
    section: {
      select: {
        section: true
        subject: { select: { name: true } }
        teacher: { select: { id: true; fullName: true; department: true } }
      }
    }
    generatedBy: { select: { id: true; fullName: true } }
  }
}>

@Injectable()
export class AttendanceReferralService {
  private readonly logger = new Logger(AttendanceReferralService.name)

  constructor(
    private readonly prisma: PrismaService,
    private readonly atRisk: AttendanceAtRiskService,
    @Optional() private readonly notifications?: NotificationsService,
  ) {}

  /**
   * F5 (WF-LD7): CHED CMO No. 40 notice-of-impending-drop referral.
   *
   * Scope: the owning teacher, an academic-oversight department head whose
   * department matches the section teacher, or a scoped super admin. The slip
   * is only generatable when the deterministic engine currently classifies the
   * student `below_threshold` or `at_risk` (no teacher discretion), and at most
   * one ACTIVE referral per (student, section) may exist.
   */
  async generateReferral(user: RequestUser, dto: GenerateAtRiskReferralDto): Promise<AtRiskReferral> {
    if (user.role !== 'teacher' && user.role !== 'super_admin') {
      throw new ForbiddenException('Referrals can only be generated by teachers and administrators')
    }
    const section = await this.prisma.section.findUnique({
      where: { id: dto.sectionId },
      select: {
        id: true,
        section: true,
        subject: { select: { name: true } },
        teacher: { select: { id: true, fullName: true, department: true } },
      },
    })
    if (!section) throw new NotFoundException('Section not found')
    await this.assertGenerateScope(user, section)

    const enrollment = await this.prisma.enrollment.findUnique({
      where: { studentId_sectionId: { studentId: dto.studentId, sectionId: section.id } },
      select: { id: true },
    })
    if (!enrollment) throw new BadRequestException('Student is not enrolled in this section')

    const classification = await this.atRisk.classifyStudent(section.id, dto.studentId)
    if (!classification) {
      throw new ConflictException({
        message: 'The deterministic engine has no attendance data for this student in this section',
        code: ErrorCode.STUDENT_NOT_AT_RISK,
      })
    }
    if (!isReferralEligible(classification)) {
      throw new ConflictException({
        message: `The student's standing is ${classification.status}; a CHED notice of impending drop requires below_threshold or at_risk`,
        code: ErrorCode.STUDENT_NOT_AT_RISK,
      })
    }

    // The (student, section) advisory lock also serializes enrollment changes,
    // so a concurrent removal cannot slip between the gate and the insert.
    const created = await this.prisma.$transaction(async (tx) => {
      await lockStudentSection(tx, dto.studentId, section.id)
      const active = await tx.atRiskReferral.findFirst({
        where: { studentId: dto.studentId, sectionId: section.id, status: { not: 'resolved' } },
        select: { id: true },
      })
      if (active) {
        throw new ConflictException({
          message: 'An active referral already exists for this student in this section',
          code: ErrorCode.REFERRAL_ACTIVE,
        })
      }
      return tx.atRiskReferral.create({
        data: {
          studentId: dto.studentId,
          sectionId: section.id,
          generatedById: user.id,
          status: 'generated',
          note: dto.note?.trim() || null,
        },
        include: REFERRAL_INCLUDE,
      })
    })

    const presented = presentReferral(created)
    await this.notifyReferralCreated(user, presented, section.teacher.id, section.teacher.department)
    await this.recordReferralAudit(user, 'attendance.referral_created', created.id, {
      studentId: dto.studentId,
      sectionId: section.id,
      status: 'generated',
      attendanceRate: classification.attendanceRate,
      engineStatus: classification.status,
    })
    return presented
  }

  /**
   * Referral queue: teachers see their own sections, academic-oversight heads
   * see their department, super admins see their administrative scope.
   */
  async listReferrals(
    user: RequestUser,
    filters: { status?: ReferralStatus; sectionId?: string } = {},
  ): Promise<AtRiskReferral[]> {
    if (user.role !== 'teacher' && user.role !== 'super_admin') {
      throw new ForbiddenException('Referrals are only visible to teachers and administrators')
    }
    const sectionWhere: Prisma.SectionWhereInput =
      user.role === 'teacher' ? this.teacherSectionWhere(user) : adminSectionWhere(user)
    const referrals = await this.prisma.atRiskReferral.findMany({
      where: {
        ...(filters.status ? { status: filters.status } : {}),
        ...(filters.sectionId ? { sectionId: filters.sectionId } : {}),
        section: sectionWhere,
      },
      orderBy: { updatedAt: 'desc' },
      take: REFERRAL_LIST_LIMIT,
      include: REFERRAL_INCLUDE,
    })
    return referrals.map((referral) => presentReferral(referral))
  }

  /**
   * Status transition. Only department heads and super admins transition the
   * queue (the generating teacher stays read-only); transitions are any→any
   * (triage flexibility, same as the system-report triage).
   */
  async updateReferralStatus(user: RequestUser, id: string, dto: UpdateAtRiskReferralDto): Promise<AtRiskReferral> {
    if (user.role !== 'teacher' && user.role !== 'super_admin') {
      throw new ForbiddenException('Only department heads and administrators can update referrals')
    }
    const referral = await this.prisma.atRiskReferral.findUnique({
      where: { id },
      include: REFERRAL_INCLUDE,
    })
    if (!referral) throw new NotFoundException('Referral not found')

    if (user.role === 'teacher') {
      const oversight = academicOversightDepartment(user)
      const allowed = oversight !== null && departmentsMatch(referral.section?.teacher?.department, oversight)
      if (!allowed) {
        throw new ForbiddenException('Only department heads and administrators can update referrals')
      }
    }
    if (user.role === 'super_admin') {
      if (!(await adminSectionInScope(user, referral.sectionId, this.prisma))) {
        throw new ForbiddenException('This referral is outside your administrative scope')
      }
    }

    const note = dto.note === undefined ? undefined : dto.note.trim() || null
    const previousStatus = referral.status
    const updated = await this.prisma.atRiskReferral.update({
      where: { id },
      data: {
        status: dto.status,
        ...(note !== undefined ? { note } : {}),
      },
      include: REFERRAL_INCLUDE,
    })

    if (
      this.notifications &&
      (dto.status === 'acknowledged' || dto.status === 'resolved') &&
      referral.generatedById !== user.id
    ) {
      await this.notifications.notify(referral.generatedById, {
        type: 'at_risk_referral',
        title: dto.status === 'resolved' ? 'Referral resolved' : 'Referral acknowledged',
        body: `${referral.student.fullName}'s impending-drop referral in ${referral.section.subject.name} (${referral.section.section}) was ${
          dto.status === 'resolved' ? 'resolved' : 'acknowledged'
        }.`,
        link: '/faculty/at-risk',
      })
    }
    await this.recordReferralAudit(user, 'attendance.referral_updated', id, {
      studentId: referral.studentId,
      sectionId: referral.sectionId,
      from: previousStatus,
      to: dto.status,
      noteUpdated: note !== undefined,
      ...(dto.status === 'resolved' ? { resolvedAt: new Date().toISOString() } : {}),
    })
    return presentReferral(updated)
  }

  // ── Private: scope plumbing ──

  private async assertGenerateScope(
    user: RequestUser,
    section: { id: string; teacher: { id: string; department: string | null } },
  ): Promise<void> {
    if (user.role === 'teacher') {
      if (section.teacher.id === user.id) return
      const oversight = academicOversightDepartment(user)
      if (oversight && departmentsMatch(section.teacher.department, oversight)) return
      throw new ForbiddenException('You can only generate referrals for your own sections')
    }
    if (!(await adminSectionInScope(user, section.id, this.prisma))) {
      throw new ForbiddenException('This section is outside your administrative scope')
    }
  }

  /** Referral sections a teacher may see: own sections, widened to their department for heads. */
  private teacherSectionWhere(user: RequestUser): Prisma.SectionWhereInput {
    const oversight = academicOversightDepartment(user)
    if (!oversight) return { teacherId: user.id }
    return {
      OR: [{ teacherId: user.id }, { teacher: { department: { equals: oversight, mode: 'insensitive' as const } } }],
    }
  }

  // ── Private: notifications + audit (fail-open) ──

  private async notifyReferralCreated(
    actor: RequestUser,
    referral: AtRiskReferral,
    sectionTeacherId: string,
    sectionTeacherDepartment: string | null,
  ): Promise<void> {
    if (!this.notifications) return
    const body = `${referral.studentName} was referred for the CHED notice of impending drop in ${referral.subjectName} (${referral.sectionName}).`
    const recipients: string[] = []
    // The section teacher hears it first (a generating teacher is not notified).
    if (sectionTeacherId && sectionTeacherId !== actor.id) {
      recipients.push(sectionTeacherId)
    }
    // When the actor is NOT a department head of that department, the head(s)
    // get the queue entry too; heads already own the queue they file into.
    if (academicOversightDepartment(actor) === null && sectionTeacherDepartment) {
      const heads = await this.prisma.user.findMany({
        where: {
          role: 'teacher',
          isActive: true,
          isDepartmentHead: true,
          department: { equals: sectionTeacherDepartment, mode: 'insensitive' },
        },
        select: { id: true },
      })
      recipients.push(...heads.map((head) => head.id).filter((id) => id !== actor.id))
    }
    const unique = [...new Set(recipients)]
    if (unique.length === 0) return
    await Promise.all(
      unique.map((userId) =>
        this.notifications!.notify(userId, {
          type: 'at_risk_referral',
          title: sectionTeacherId === userId ? 'At-risk referral filed' : 'CHED notice referral filed',
          body,
          link: '/faculty/at-risk',
        }),
      ),
    )
  }

  private async recordReferralAudit(
    user: RequestUser,
    action: string,
    referralId: string,
    metadata: Prisma.InputJsonValue,
  ): Promise<void> {
    try {
      await this.prisma.auditLog.create({
        data: {
          actorId: user.id,
          actorRole: user.role,
          action,
          entityType: 'at_risk_referral',
          entityId: referralId,
          metadata,
        },
      })
    } catch (error) {
      this.logger.warn(`Could not write ${action} audit row for referral ${referralId}: ${String(error)}`)
    }
  }
}

const REFERRAL_INCLUDE = {
  student: { select: { id: true, studentId: true, fullName: true } },
  section: {
    select: {
      section: true,
      subject: { select: { name: true } },
      teacher: { select: { id: true, fullName: true, department: true } },
    },
  },
  generatedBy: { select: { id: true, fullName: true } },
} satisfies Prisma.AtRiskReferralInclude

function presentReferral(referral: ReferralRow): AtRiskReferral {
  return {
    id: referral.id,
    studentId: referral.studentId,
    studentName: referral.student.fullName,
    ...(referral.student.studentId ? { studentNumber: referral.student.studentId } : {}),
    sectionId: referral.sectionId,
    sectionName: referral.section.section,
    subjectName: referral.section.subject.name,
    professorName: referral.section.teacher.fullName,
    generatedById: referral.generatedById,
    generatedByName: referral.generatedBy.fullName,
    status: referral.status as ReferralStatus,
    ...(referral.note ? { note: referral.note } : {}),
    createdAt: referral.createdAt.toISOString(),
    updatedAt: referral.updatedAt.toISOString(),
  }
}

/** Case-insensitive department equality shared with the docs scope helpers. */
export function departmentsMatch(left: string | null | undefined, right: string | null | undefined): boolean {
  const normalizedLeft = left?.trim().toLowerCase()
  const normalizedRight = right?.trim().toLowerCase()
  return Boolean(normalizedLeft && normalizedRight && normalizedLeft === normalizedRight)
}
